#!/usr/bin/env python3
"""Compile the reference app's design tokens and UI text into typed TypeScript.

Reads `ui/tokens.jsonc` and every `locales/<language>.jsonc` beside this script, and writes
`ui/tokens.generated.ts` and `locales/strings.generated.ts`. `--check` writes nothing and exits 1
when either generated file differs from what the sources produce, so the modules the screens
import cannot drift from the files people edit.

Usage: python3 generate-ui-resources.py [--check]

What is refused, and why each refusal fails generation instead of being skipped:
  * A color role that names a color React Native 0.87's `PlatformColor` does not resolve. An
    unknown name renders as clear on iOS, which no screenshot of a light-mode default would show.
  * A text style that names a step missing from the type ramp, and any token group or field this
    script does not know. A typo must not become a style that silently does nothing.
  * A message whose ICU syntax does not parse, a plural or select without an `other` branch, `#`
    outside a plural, and an argument used as two different kinds in one message.
  * A language whose keys or placeholders differ from English, and a language with no plural rule.
  * A duplicate key anywhere in either file. JSON parsers keep the last one without saying so.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOKENS_SOURCE = HERE / "ui/tokens.jsonc"
TOKENS_OUTPUT = HERE / "ui/tokens.generated.ts"
LOCALES = HERE / "locales"
STRINGS_OUTPUT = HERE / "locales/strings.generated.ts"
FALLBACK_LOCALE = "en"
HEADER = "// Generated by generate-ui-resources.py from {source}. Do not edit; edit the source and run it."

# The semantic color names React Native 0.87 resolves on iOS: `RCTSemanticColorsMap` in
# react-native/React/Base/RCTConvert.mm, with each Objective-C name's `Color` suffix dropped.
PLATFORM_COLORS = {
    "label", "secondaryLabel", "tertiaryLabel", "quaternaryLabel",
    "systemFill", "secondarySystemFill", "tertiarySystemFill", "quaternarySystemFill",
    "placeholderText",
    "systemBackground", "secondarySystemBackground", "tertiarySystemBackground",
    "systemGroupedBackground", "secondarySystemGroupedBackground", "tertiarySystemGroupedBackground",
    "separator", "opaqueSeparator", "link", "darkText", "lightText",
    "systemBlue", "systemBrown", "systemCyan", "systemGreen", "systemIndigo", "systemMint",
    "systemOrange", "systemPink", "systemPurple", "systemRed", "systemTeal", "systemYellow",
    "systemGray", "systemGray2", "systemGray3", "systemGray4", "systemGray5", "systemGray6",
    "clear",
}
# UIKit's non-adaptive colors, which `PlatformColor` cannot resolve. See the token file.
FIXED_COLORS = {"white": (255, 255, 255), "black": (0, 0, 0)}
TEXT_STYLES = {"largeTitle", "title1", "title2", "title3", "headline", "body", "callout",
               "subheadline", "footnote", "caption1", "caption2"}
FONT_WEIGHTS = {"100", "200", "300", "400", "500", "600", "700", "800", "900"}
NUMBER_GROUPS = ("spacing", "radius", "border", "opacity", "elevation")
TOKEN_GROUPS = ("color", "typeRamp", "text") + NUMBER_GROUPS + ("size",)
IDENTIFIER = re.compile(r"[A-Za-z][A-Za-z0-9]*\Z")
KEY_SEGMENT = re.compile(r"[A-Za-z0-9][A-Za-z0-9_]*\Z")
# CLDR cardinal plural rules, as TypeScript, for each language this app ships. A language with no
# rule here cannot be generated: a wrong plural is a wrong sentence, so there is no default rule.
PLURAL_RULES = {
    "en": "(count) => (count === 1 ? 'one' : 'other')",
}


def fail(message: str) -> None:
    print(f"generate-ui-resources: {message}", file=sys.stderr)
    sys.exit(2)


def strip_jsonc(text: str, where: str) -> str:
    """JSON with `//` and `/* */` comments and trailing commas, as plain JSON. Strings are kept
    exactly; a comment marker inside a string is text."""
    out: list[str] = []
    index, length = 0, len(text)
    while index < length:
        char = text[index]
        if char == '"':
            end = index + 1
            while end < length and text[end] != '"':
                end += 2 if text[end] == "\\" else 1
            if end >= length:
                fail(f"{where}: unterminated string")
            out.append(text[index:end + 1])
            index = end + 1
        elif text.startswith("//", index):
            end = text.find("\n", index)
            index = length if end == -1 else end
        elif text.startswith("/*", index):
            end = text.find("*/", index + 2)
            if end == -1:
                fail(f"{where}: unterminated block comment")
            out.append(" ")
            index = end + 2
        elif char in "}]":
            while out and out[-1].isspace():
                out.pop()
            if out and out[-1] == ",":
                out.pop()
            out.append(char)
            index += 1
        else:
            out.append(char)
            index += 1
    return "".join(out)


def load_jsonc(path: Path) -> dict:
    where = path.relative_to(HERE).as_posix()

    def unique(pairs: list[tuple[str, object]]) -> dict:
        seen: dict = {}
        for key, value in pairs:
            if key in seen:
                fail(f"{where}: duplicate key {key!r}")
            seen[key] = value
        return seen

    try:
        document = json.loads(strip_jsonc(path.read_text(encoding="utf-8"), where),
                              object_pairs_hook=unique)
    except json.JSONDecodeError as error:
        fail(f"{where}: {error}")
    if not isinstance(document, dict):
        fail(f"{where}: the top level is not an object")
    return document


def ts_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def number(value: object, where: str) -> str:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        fail(f"{where}: expected a number, found {value!r}")
    return repr(value) if isinstance(value, float) else str(value)


def name(value: str, where: str) -> str:
    if not IDENTIFIER.match(value):
        fail(f"{where}: {value!r} is not a token name (letters and digits, starting with a letter)")
    return value


# --- Tokens ----------------------------------------------------------------------------------------

def generate_tokens() -> str:
    tokens = load_jsonc(TOKENS_SOURCE)
    unknown = set(tokens) - set(TOKEN_GROUPS)
    missing = set(TOKEN_GROUPS) - set(tokens)
    if unknown or missing:
        fail(f"ui/tokens.jsonc: unknown groups {sorted(unknown)}, missing groups {sorted(missing)}")
    for group in TOKEN_GROUPS:
        if not isinstance(tokens[group], dict) or not tokens[group]:
            fail(f"ui/tokens.jsonc: {group} is not a non-empty object")
    elevation = tokens["elevation"]
    lines = [HEADER.format(source="ui/tokens.jsonc"), "",
             "import {PlatformColor} from 'react-native';", ""]

    lines.append("/** Color roles. Adaptive roles resolve iOS system colors; see ui/tokens.jsonc. */")
    lines.append("export const color = {")
    for role, spec in tokens["color"].items():
        where = f"color.{name(role, 'color')}"
        if not isinstance(spec, dict):
            fail(f"{where}: expected an object")
        if set(spec) == {"ios"}:
            if spec["ios"] not in PLATFORM_COLORS:
                fail(f"{where}: {spec['ios']!r} is not a color React Native 0.87's PlatformColor resolves")
            value = f"PlatformColor({ts_string(spec['ios'])})"
        elif set(spec) in ({"fixed"}, {"fixed", "opacity"}):
            if spec["fixed"] not in FIXED_COLORS:
                fail(f"{where}: fixed color {spec['fixed']!r} is not one of {sorted(FIXED_COLORS)}")
            red, green, blue = FIXED_COLORS[spec["fixed"]]
            if "opacity" in spec:
                if spec["opacity"] not in elevation:
                    fail(f"{where}: opacity names {spec['opacity']!r}, which elevation does not define")
                alpha = number(elevation[spec["opacity"]], f"elevation.{spec['opacity']}")
                value = ts_string(f"rgba({red}, {green}, {blue}, {alpha})")
            else:
                value = ts_string(f"#{red:02X}{green:02X}{blue:02X}")
        else:
            fail(f"{where}: give exactly one of \"ios\" or \"fixed\" (with an optional \"opacity\")")
        lines.append(f"  {role}: {value},")
    lines += ["} as const;", ""]

    ramp: dict[str, tuple[str, str]] = {}
    for style, spec in tokens["typeRamp"].items():
        where = f"typeRamp.{style}"
        if style not in TEXT_STYLES:
            fail(f"{where}: {style!r} is not an iOS text style")
        if not isinstance(spec, dict) or set(spec) != {"fontSize", "lineHeight"}:
            fail(f"{where}: expected exactly fontSize and lineHeight")
        ramp[style] = (number(spec["fontSize"], where), number(spec["lineHeight"], where))
    lines.append("/** Text styles, each on a step of the iOS Dynamic Type ramp. */")
    lines.append("export const text = {")
    for role, spec in tokens["text"].items():
        where = f"text.{name(role, 'text')}"
        if not isinstance(spec, dict) or not {"style", "fontWeight"} <= set(spec) <= {
                "style", "fontWeight", "letterSpacing"}:
            fail(f"{where}: expected style, fontWeight and an optional letterSpacing")
        if spec["style"] not in ramp:
            fail(f"{where}: style {spec['style']!r} is not in typeRamp")
        if spec["fontWeight"] not in FONT_WEIGHTS:
            fail(f"{where}: fontWeight {spec['fontWeight']!r} is not one of {sorted(FONT_WEIGHTS)}")
        size, height = ramp[spec["style"]]
        fields = [f"fontSize: {size}", f"lineHeight: {height}",
                  f"fontWeight: {ts_string(spec['fontWeight'])}"]
        if "letterSpacing" in spec:
            fields.append(f"letterSpacing: {number(spec['letterSpacing'], where)}")
        lines.append(f"  {role}: {{{', '.join(fields)}}},")
    lines += ["} as const;", ""]

    for group in NUMBER_GROUPS:
        lines.append(f"export const {group} = {{")
        for key, value in tokens[group].items():
            lines.append(f"  {name(key, group)}: {number(value, f'{group}.{key}')},")
        lines += ["} as const;", ""]

    lines.append("export const size = {")
    for key, value in tokens["size"].items():
        where = f"size.{name(key, 'size')}"
        if isinstance(value, str):
            if not re.fullmatch(r"\d+(?:\.\d+)?%", value):
                fail(f"{where}: a string size must be a percentage")
            lines.append(f"  {key}: {ts_string(value)},")
        else:
            lines.append(f"  {key}: {number(value, where)},")
    lines += ["} as const;", ""]
    return "\n".join(lines)


# --- Messages --------------------------------------------------------------------------------------
# A message compiles to a string when it has no ICU syntax, and otherwise to a list of parts:
#   "text"                                  literal text
#   ["arg", name]                           a value
#   ["plural", name, {selector: message}]   a count; selectors are =N, a CLDR category or other
#   ["select", name, {selector: message}]   one branch per value, and other
#   ["#"]                                   the count, inside a plural branch


class Parser:
    def __init__(self, text: str, where: str):
        self.text, self.where, self.index = text, where, 0
        self.arguments: dict[str, str] = {}

    def error(self, message: str) -> None:
        fail(f"{self.where}: {message} at character {self.index}: {self.text!r}")

    def message(self, in_plural: bool, closing: bool) -> list:
        parts: list = []
        literal: list[str] = []

        def flush() -> None:
            if literal:
                parts.append("".join(literal))
                literal.clear()

        while self.index < len(self.text):
            char = self.text[self.index]
            if char == "'":
                following = self.text[self.index + 1:self.index + 2]
                if following == "'":
                    literal.append("'")
                    self.index += 2
                elif following and following in "{}#" and (following != "#" or in_plural):
                    end = self.text.find("'", self.index + 1)
                    if end == -1:
                        self.error("unterminated quoted text")
                    literal.append(self.text[self.index + 1:end])
                    self.index = end + 1
                else:
                    literal.append("'")
                    self.index += 1
            elif char == "{":
                flush()
                parts.append(self.argument())
            elif char == "}":
                if not closing:
                    self.error("unmatched }")
                break
            elif char == "#" and in_plural:
                flush()
                parts.append(["#"])
                self.index += 1
            else:
                literal.append(char)
                self.index += 1
        flush()
        return parts

    def skip(self) -> None:
        while self.index < len(self.text) and self.text[self.index].isspace():
            self.index += 1

    def word(self) -> str:
        self.skip()
        match = re.compile(r"=?[A-Za-z0-9_]+").match(self.text, self.index)
        if not match:
            self.error("expected a name")
        self.index = match.end()
        return match.group(0)

    def expect(self, char: str) -> None:
        self.skip()
        if self.text[self.index:self.index + 1] != char:
            self.error(f"expected {char!r}")
        self.index += 1

    def record(self, argument: str, kind: str) -> None:
        if not IDENTIFIER.match(argument):
            self.error(f"argument {argument!r} is not an identifier")
        if self.arguments.setdefault(argument, kind) != kind:
            self.error(f"argument {argument!r} is used both as {self.arguments[argument]} and {kind}")

    def argument(self) -> list:
        self.index += 1
        argument = self.word()
        self.skip()
        if self.text[self.index:self.index + 1] == "}":
            self.index += 1
            self.record(argument, "arg")
            return ["arg", argument]
        self.expect(",")
        kind = self.word()
        if kind not in ("plural", "select"):
            self.error(f"argument type {kind!r} is not supported; use plural or select")
        self.record(argument, kind)
        self.expect(",")
        branches: dict[str, object] = {}
        while True:
            self.skip()
            if self.text[self.index:self.index + 1] == "}":
                self.index += 1
                break
            selector = self.word()
            if selector in branches:
                self.error(f"selector {selector!r} repeats")
            if kind == "select" and selector.startswith("="):
                self.error("a select selector cannot be =N")
            if kind == "plural" and not (re.fullmatch(r"=\d+", selector) or selector in (
                    "zero", "one", "two", "few", "many", "other")):
                self.error(f"plural selector {selector!r} is not =N or a CLDR category")
            self.expect("{")
            branches[selector] = compact(self.message(in_plural=kind == "plural", closing=True))
            self.expect("}")
        if "other" not in branches:
            self.error(f"{kind} {argument!r} has no other branch")
        return [kind, argument, branches]


def compact(parts: list):
    """A message with only literal text is one string; anything else stays a list of parts."""
    if all(isinstance(part, str) for part in parts):
        return "".join(parts)
    return parts


def compile_message(text: str, where: str) -> tuple[object, dict[str, str]]:
    parser = Parser(text, where)
    parts = parser.message(in_plural=False, closing=False)
    if parser.index != len(text):
        parser.error("trailing text")
    return compact(parts), parser.arguments


def flatten(node: dict, prefix: str, where: str, out: dict[str, str]) -> None:
    for key, value in node.items():
        if not KEY_SEGMENT.match(key):
            fail(f"{where}: key segment {key!r} is not letters, digits and underscores")
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            flatten(value, path, where, out)
        elif isinstance(value, str):
            out[path] = value
        else:
            fail(f"{where}: {path} is neither a message nor a group")


def generate_strings() -> str:
    catalogs: dict[str, tuple[dict, dict[str, str]]] = {}
    for path in sorted(LOCALES.glob("*.jsonc")):
        code = path.stem
        where = f"locales/{path.name}"
        if not re.fullmatch(r"[a-z]{2,3}", code):
            fail(f"{where}: the file name must be a lowercase ISO 639 language code")
        if code not in PLURAL_RULES:
            fail(f"{where}: no plural rule for {code!r}; add its CLDR rule to PLURAL_RULES")
        document = load_jsonc(path)
        metadata = document.pop("@metadata", None)
        if not isinstance(metadata, dict) or set(metadata) != {"formatLocale"} or not isinstance(
                metadata["formatLocale"], str):
            fail(f"{where}: @metadata must hold exactly formatLocale, a BCP 47 tag")
        messages: dict[str, str] = {}
        flatten(document, "", where, messages)
        catalogs[code] = (metadata, messages)
    if FALLBACK_LOCALE not in catalogs:
        fail(f"locales/{FALLBACK_LOCALE}.jsonc is missing; it is the declared fallback")

    compiled: dict[str, dict[str, object]] = {}
    signatures: dict[str, dict[str, str]] = {}
    for code, (_, messages) in catalogs.items():
        compiled[code] = {}
        for key, text in messages.items():
            compiled[code][key], arguments = compile_message(text, f"locales/{code}.jsonc {key}")
            if code == FALLBACK_LOCALE:
                signatures[key] = arguments
            elif key in signatures and arguments != signatures[key]:
                fail(f"locales/{code}.jsonc {key}: placeholders {arguments} differ from English "
                     f"{signatures[key]}")
    keys = list(compiled[FALLBACK_LOCALE])
    for code in compiled:
        if set(compiled[code]) != set(keys):
            fail(f"locales/{code}.jsonc: keys differ from English: missing "
                 f"{sorted(set(keys) - set(compiled[code]))}, extra {sorted(set(compiled[code]) - set(keys))}")

    value_types = {"arg": "string | number", "plural": "number", "select": "string"}
    lines = [HEADER.format(source="locales/*.jsonc"), "",
             "/** One compiled message: plain text, or ICU parts. Rendered by `t` in i18n.ts. */",
             "export type Message = string | readonly Part[];",
             "export type Part = string | readonly ['#'] | readonly ['arg', string]",
             "  | readonly ['plural' | 'select', string, {readonly [selector: string]: Message}];", "",
             "/** Every message key, with the values its message needs (undefined: none). */",
             "export type MessageValues = {"]
    for key in keys:
        arguments = signatures[key]
        if arguments:
            fields = "; ".join(f"readonly {argument}: {value_types[kind]}"
                               for argument, kind in sorted(arguments.items()))
            lines.append(f"  readonly {ts_string(key)}: {{{fields}}};")
        else:
            lines.append(f"  readonly {ts_string(key)}: undefined;")
    codes = " | ".join(f"'{code}'" for code in compiled)
    lines += ["};",
              "export type MessageKey = keyof MessageValues;",
              f"export type LocaleCode = {codes};",
              "export type LocaleDefinition = {",
              "  /** The BCP 47 tag dates are formatted with. */",
              "  readonly formatLocale: string;",
              "  /** The CLDR cardinal plural category of a count. */",
              "  readonly plural: (count: number) => string;",
              "  readonly messages: {readonly [K in MessageKey]: Message};",
              "};", "",
              "/** The one declared fallback: used when the device language has no catalog. */",
              f"export const fallbackLocale: LocaleCode = '{FALLBACK_LOCALE}';", "",
              "export const locales: {readonly [C in LocaleCode]: LocaleDefinition} = {"]
    for code, (metadata, _) in catalogs.items():
        lines += [f"  {code}: {{",
                  f"    formatLocale: {ts_string(metadata['formatLocale'])},",
                  f"    plural: {PLURAL_RULES[code]},",
                  "    messages: {"]
        for key in keys:
            lines.append(f"      {ts_string(key)}: {json.dumps(compiled[code][key], ensure_ascii=False)},")
        lines += ["    },", "  },"]
    lines += ["};", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the generated modules are stale")
    arguments = parser.parse_args()
    outputs = {TOKENS_OUTPUT: generate_tokens(), STRINGS_OUTPUT: generate_strings()}
    if arguments.check:
        stale = [path for path, text in outputs.items()
                 if not path.exists() or path.read_text(encoding="utf-8") != text]
        for path in stale:
            print(f"stale: {path.relative_to(HERE).as_posix()}", file=sys.stderr)
        sys.exit(1 if stale else 0)
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(HERE).as_posix()}")


if __name__ == "__main__":
    main()
